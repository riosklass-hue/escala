// Helper para criar componentes a partir das matrizes oficiais
function criarComponentesMatriz(
  sigla: string,
  matrizId: string,
  concluidas: number,
  emAndamento: number,
  profTitular?: { id: string; nome: string }
): ComponenteDaTurma[] {
  const matriz = MATRIZES_CURSOS_OFICIAIS.find((m) => m.id === matrizId);
  if (!matriz) return [];

  return matriz.unidades.map((uc, idx) => {
    let status: ComponenteDaTurma['status'] = 'A MINISTRAR';
    let professorId: string | undefined = undefined;
    let professorNome: string | undefined = undefined;
    let dataInicio: string | undefined = undefined;
    let dataFim: string | undefined = undefined;
    let dataConclusao: string | undefined = undefined;

    if (idx < concluidas) {
      status = 'CONCLUÍDO';
      professorId = profTitular?.id;
      professorNome = profTitular?.nome;
      dataInicio = '01/08/2026';
      dataFim = '28/08/2026';
      dataConclusao = '28/08/2026';
    } else if (idx < concluidas + emAndamento) {
      status = 'EM ANDAMENTO';
      professorId = profTitular?.id;
      professorNome = profTitular?.nome;
      dataInicio = '01/09/2026';
      dataFim = '30/09/2026';
    }

    return {
      id: `c-${sigla.toLowerCase()}-${idx + 1}`,
      nome: uc.nome,
      cargaHoraria: uc.cargaHoraria,
      status,
      professorId,
      professorNome,
      dataInicio,
      dataFim,
      dataConclusao,
    };
  });
}

